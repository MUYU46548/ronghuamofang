export function hasAckedDisclaimer() {
  try { return !!localStorage.getItem(DISCLAIMER_ACK_KEY); } catch { return false; }
}

export function ackedDisclaimerAt() {
  try {
    const v = JSON.parse(localStorage.getItem(DISCLAIMER_ACK_KEY) || "null");
    return v && v.at ? v.at : "";
  } catch { return ""; }
}
